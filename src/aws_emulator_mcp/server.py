"""MCP stdio server for the OFFICIAL AWS Emulator (aws/aws-emulator).
No external Python packages. Never calls real AWS.
"""
from __future__ import annotations
import configparser, datetime, hashlib, hmac, json, os, re, shutil, signal, ssl, subprocess, sys, time
from pathlib import Path
from urllib.error import HTTPError, URLError
from urllib.parse import quote, urlencode
from urllib.request import Request, urlopen
from xml.etree import ElementTree as ET

PORT=int(os.environ.get("AWS_EMULATOR_PORT","9297"))
if not 1024 <= PORT <= 65535: raise SystemExit("Invalid AWS_EMULATOR_PORT")
ENDPOINT=f"https://127.0.0.1:{PORT}"
CREDDIR=Path.home()/".aws"/"emulator"/str(PORT)
WORKDIR=Path.home()/".local"/"share"/"aws-emulator-mcp"
PIDFILE=WORKDIR/f"emulator-{PORT}.pid"
REGION="us-east-1"
MAX_BYTES=1_048_576

class LocalError(RuntimeError): pass

def ssl_context():
    pem=CREDDIR/"ca.pem"
    if not pem.is_file(): raise LocalError("Emulator certificate absent; start official AWS Emulator")
    return ssl.create_default_context(cafile=str(pem))

def emulator_keys():
    path=CREDDIR/"emulator_credentials"
    if not path.is_file(): raise LocalError("Emulator credentials absent")
    cp=configparser.ConfigParser()
    cp.read(path)
    if not cp.sections(): raise LocalError("Emulator credentials file invalid")
    d=cp["default"] if cp.has_section("default") else cp[cp.sections()[0]]
    key=d.get("aws_access_key_id","")
    secret=d.get("aws_secret_access_key","")
    if not key.startswith("EMULATOR") or not secret:
        raise LocalError("Refusing credentials not generated by AWS Emulator")
    return key,secret,d.get("aws_session_token","")

def hmac256(key,data): return hmac.new(key,data.encode(),hashlib.sha256).digest()

def signed_headers(service,method,path,query,body,extra=None,when=None):
    key,secret,token=emulator_keys()
    when=when or datetime.datetime.now(datetime.timezone.utc)
    date=when.strftime("%Y%m%d")
    timestamp=when.strftime("%Y%m%dT%H%M%SZ")
    payload_hash=hashlib.sha256(body).hexdigest()
    headers={"host":f"127.0.0.1:{PORT}","x-amz-date":timestamp,"x-amz-content-sha256":payload_hash}
    if token: headers["x-amz-security-token"]=token
    for k,v in (extra or {}).items(): headers[k.lower()]=str(v).strip()
    cleanpath=quote(path,safe="/-_.~")
    cleanquery=urlencode(sorted((query or {}).items()),safe="-_.~",quote_via=quote)
    ordered=sorted(headers)
    names=";".join(ordered)
    lines="".join(f"{k}:{' '.join(headers[k].split())}\n" for k in ordered)
    canonical="\n".join([method.upper(),cleanpath,cleanquery,lines,names,payload_hash])
    scope=f"{date}/{REGION}/{service}/aws4_request"
    string_to_sign="\n".join(["AWS4-HMAC-SHA256",timestamp,scope,hashlib.sha256(canonical.encode()).hexdigest()])
    secretkey=hmac256(hmac256(hmac256(hmac256(("AWS4"+secret).encode(),date),REGION),service),"aws4_request")
    signature=hmac.new(secretkey,string_to_sign.encode(),hashlib.sha256).hexdigest()
    headers["authorization"]=f"AWS4-HMAC-SHA256 Credential={key}/{scope}, SignedHeaders={names}, Signature={signature}"
    return headers,cleanpath,cleanquery

def request(method,path="/",service=None,body=b"",headers=None,query=None):
    context=ssl_context()
    if service:
        hdr,urlpath,urlquery=signed_headers(service,method,path,query,body,headers)
    else:
        hdr,urlpath,urlquery=headers or {},quote(path,safe="/-_.~"),urlencode(query or {})
    url=ENDPOINT+urlpath+("?"+urlquery if urlquery else "")
    req=Request(url,data=body if method in ("POST","PUT") else None,headers=hdr,method=method)
    try:
        with urlopen(req,context=context,timeout=8) as r:
            content=r.read(MAX_BYTES+1)
            if len(content)>MAX_BYTES: raise LocalError("Response exceeds 1 MiB limit")
            return {"status":r.status,"headers":dict(r.headers),"body":content}
    except HTTPError as e:
        raise LocalError(f"Emulator HTTP {e.code}: {e.read(4096).decode(errors='replace')}") from e
    except URLError as e:
        raise LocalError(f"Emulator not reachable: {e.reason}") from e

def health():
    try:
        r=request("GET","/__admin/health")
        return {"running":r["status"]==200,"endpoint":ENDPOINT,"body":r["body"].decode(errors="replace")}
    except (LocalError,OSError) as e:
        return {"running":False,"endpoint":ENDPOINT,"detail":str(e)}

def emulator_binary():
    p=Path.home()/".local"/"bin"/"aws-emulator"
    return str(p) if p.exists() else shutil.which("aws-emulator")

def status():
    return {"installed":bool(emulator_binary()),"port":PORT,**health()}

def start():
    if health()["running"]: return {"action":"already_running",**status()}
    binary=emulator_binary()
    if not binary: raise LocalError("Official emulator not installed: run scripts/install_wsl.sh")
    WORKDIR.mkdir(parents=True,exist_ok=True)
    with (WORKDIR/f"emulator-{PORT}.log").open("ab") as log:
        proc=subprocess.Popen([binary,"-p",str(PORT),"--telemetry","off"],
              stdin=subprocess.DEVNULL,stdout=log,stderr=subprocess.STDOUT,
              start_new_session=True,cwd=WORKDIR)
    PIDFILE.write_text(str(proc.pid))
    for i in range(40):
        if proc.poll() is not None:
            raise LocalError(f"Emulator exited {proc.returncode}; check emulator-{PORT}.log")
        if health()["running"]: return {"action":"started","pid":proc.pid,**status()}
        time.sleep(0.25)
    raise LocalError("Emulator startup timeout; inspect local emulator log")

def stop():
    if not PIDFILE.is_file(): raise LocalError("No MCP-managed emulator; refusing to stop other processes")
    pid=int(PIDFILE.read_text().strip())
    path=Path(f"/proc/{pid}/cmdline")
    if not path.exists():
        PIDFILE.unlink(missing_ok=True)
        return {"action":"already_stopped"}
    command=path.read_bytes().replace(b"\0",b" ").decode(errors="replace")
    if "aws-emulator" not in command or f"-p {PORT}" not in command:
        raise LocalError("PID changed: refusing to terminate unrelated process")
    os.kill(pid,signal.SIGTERM)
    PIDFILE.unlink(missing_ok=True)
    return {"action":"stop_requested","pid":pid}

def identity():
    payload=urlencode({"Action":"GetCallerIdentity","Version":"2011-06-15"}).encode()
    r=request("POST","/",service="sts",body=payload,
              headers={"content-type":"application/x-www-form-urlencoded; charset=utf-8"})
    d={x.tag.split("}")[-1]:x.text for x in ET.fromstring(r["body"]).iter()
       if x.tag.split("}")[-1] in ("Account","Arn","UserId")}
    if d.get("Account")!="000000000000":
        raise LocalError("Account is not the isolated emulator account")
    return d

def check_bucket(bucket):
    if not isinstance(bucket,str) or not re.fullmatch(r"[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]",bucket) or ".." in bucket:
        raise LocalError("Invalid S3 bucket name")
    return bucket

def check_table(table):
    if not isinstance(table,str) or not re.fullmatch(r"[A-Za-z0-9_.-]{3,255}",table):
        raise LocalError("Invalid DynamoDB table name")
    return table

def object_path(bucket,key):
    check_bucket(bucket)
    if not isinstance(key,str) or not 1<=len(key)<=1024 or key.startswith("/"):
        raise LocalError("Invalid object key")
    return f"/{bucket}/{key}"

def s3_create_bucket(bucket):
    bucket=check_bucket(bucket)
    r=request("PUT",f"/{bucket}",service="s3")
    return {"bucket":bucket,"status":r["status"]}

def s3_list_buckets():
    r=request("GET","/",service="s3")
    root=ET.fromstring(r["body"])
    buckets=[]
    for node in root.iter():
        if node.tag.split("}")[-1]=="Buckets":
            for bucket in node:
                for field in bucket:
                    if field.tag.split("}")[-1]=="Name": buckets.append(field.text or "")
    return {"buckets":buckets}

def s3_put_object(bucket,key,text):
    if not isinstance(text,str) or len(text.encode())>65536:
        raise LocalError("text must be at most 64 KiB")
    r=request("PUT",object_path(bucket,key),service="s3",body=text.encode(),
              headers={"content-type":"text/plain; charset=utf-8"})
    return {"bucket":bucket,"key":key,"status":r["status"],"etag":r["headers"].get("ETag")}

def s3_get_object(bucket,key):
    r=request("GET",object_path(bucket,key),service="s3")
    return {"bucket":bucket,"key":key,"text":r["body"].decode("utf-8"),"bytes":len(r["body"])}

def s3_delete_object(bucket,key):
    r=request("DELETE",object_path(bucket,key),service="s3")
    return {"deleted":True,"status":r["status"]}

def dynamo(operation,payload):
    body=json.dumps(payload,separators=(",",":")).encode()
    r=request("POST","/",service="dynamodb",body=body,headers={
        "content-type":"application/x-amz-json-1.0",
        "x-amz-target":"DynamoDB_20120810."+operation})
    return json.loads(r["body"]) if r["body"] else {}

def dynamodb_create_table(table):
    check_table(table)
    data=dynamo("CreateTable",{"TableName":table,
        "AttributeDefinitions":[{"AttributeName":"id","AttributeType":"S"}],
        "KeySchema":[{"AttributeName":"id","KeyType":"HASH"}],
        "BillingMode":"PAY_PER_REQUEST"})
    return {"table":table,"description":data.get("TableDescription",{})}

def dynamodb_put_item(table,item_id,message):
    check_table(table)
    data=dynamo("PutItem",{"TableName":table,"Item":{
        "id":{"S":str(item_id)},"message":{"S":str(message)}}})
    return {"table":table,"id":str(item_id),"result":data}

def dynamodb_get_item(table,item_id):
    check_table(table)
    return dynamo("GetItem",{"TableName":table,"Key":{"id":{"S":str(item_id)}}})

def dynamodb_delete_table(table):
    check_table(table)
    return dynamo("DeleteTable",{"TableName":table})

def spec(name,description,properties=None,required=()):
    return {"name":name,"description":description,
      "inputSchema":{"type":"object","properties":properties or {},
                     "required":list(required),"additionalProperties":False}}
STR={"type":"string"}
TOOLS=[
    spec("emulator_status","Inspect official local AWS Emulator status"),
    spec("emulator_start","Start official AWS Emulator with telemetry disabled"),
    spec("emulator_stop","Stop only an MCP-managed emulator process"),
    spec("emulator_health","Check local HTTPS emulator health"),
    spec("emulator_identity","Verify isolated STS account 000000000000"),
    spec("s3_create_bucket","Create emulated S3 bucket",{"bucket":STR},("bucket",)),
    spec("s3_list_buckets","List emulated S3 buckets"),
    spec("s3_put_object","Put UTF-8 text in emulated S3",{"bucket":STR,"key":STR,"text":STR},("bucket","key","text")),
    spec("s3_get_object","Read UTF-8 text from emulated S3",{"bucket":STR,"key":STR},("bucket","key")),
    spec("s3_delete_object","Delete emulated S3 object",{"bucket":STR,"key":STR},("bucket","key")),
    spec("dynamodb_create_table","Create DynamoDB table with string id key",{"table":STR},("table",)),
    spec("dynamodb_put_item","Store id and message strings",{"table":STR,"item_id":STR,"message":STR},("table","item_id","message")),
    spec("dynamodb_get_item","Read DynamoDB item",{"table":STR,"item_id":STR},("table","item_id")),
    spec("dynamodb_delete_table","Delete emulated DynamoDB table",{"table":STR},("table",)),
]
FUNCTIONS=dict(emulator_status=status,emulator_start=start,emulator_stop=stop,
    emulator_health=health,emulator_identity=identity,
    s3_create_bucket=s3_create_bucket,s3_list_buckets=s3_list_buckets,
    s3_put_object=s3_put_object,s3_get_object=s3_get_object,s3_delete_object=s3_delete_object,
    dynamodb_create_table=dynamodb_create_table,dynamodb_put_item=dynamodb_put_item,
    dynamodb_get_item=dynamodb_get_item,dynamodb_delete_table=dynamodb_delete_table)

def handle(msg):
    method=msg.get("method")
    rid=msg.get("id")
    if rid is None: return None
    if method=="initialize":
        offered=(msg.get("params") or {}).get("protocolVersion")
        version=offered if offered in ("2025-03-26","2025-06-18","2025-11-25") else "2025-06-18"
        result={"protocolVersion":version,"capabilities":{"tools":{"listChanged":False}},
                "serverInfo":{"name":"aws-emulator-mcp","version":"0.1.0"}}
    elif method=="ping": result={}
    elif method=="tools/list": result={"tools":TOOLS}
    elif method=="tools/call":
        params=msg.get("params") or {}
        name=params.get("name")
        if name not in FUNCTIONS:
            return {"jsonrpc":"2.0","id":rid,"error":{"code":-32602,"message":"Unknown tool"}}
        args=params.get("arguments") or {}
        schema=next(t["inputSchema"] for t in TOOLS if t["name"]==name)
        if not isinstance(args,dict) or set(args)-set(schema["properties"]) or any(k not in args for k in schema["required"]):
            return {"jsonrpc":"2.0","id":rid,"error":{"code":-32602,"message":"Invalid arguments"}}
        try:
            value=FUNCTIONS[name](**args)
            result={"content":[{"type":"text","text":json.dumps(value,ensure_ascii=False)}],"isError":False}
        except (LocalError,OSError,ValueError,TypeError,UnicodeError,ET.ParseError) as exc:
            result={"content":[{"type":"text","text":str(exc)}],"isError":True}
    else:
        return {"jsonrpc":"2.0","id":rid,"error":{"code":-32601,"message":"Method not found"}}
    return {"jsonrpc":"2.0","id":rid,"result":result}

def main():
    for line in sys.stdin:
        if not line.strip(): continue
        try:
            value=handle(json.loads(line))
            if value is not None: print(json.dumps(value,ensure_ascii=False,separators=(",",":")),flush=True)
        except Exception as exc:
            print(f"[aws-emulator-mcp] protocol error: {exc}",file=sys.stderr,flush=True)

if __name__=="__main__": main()
