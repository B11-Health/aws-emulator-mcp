def doctor():
    """Read-only diagnostics with actionable guidance; never exposes credentials."""
    checks=[]
    def row(name,ok,remedy=""):
        checks.append({"check":name,"passed":bool(ok),"fix":"" if ok else remedy})
    executable=emulator_binary()
    row("official emulator executable",bool(executable),
        "Run install.cmd on Windows or bash install.sh on Linux.")
    if executable:
        try:
            details=subprocess.run([executable,"--version"],capture_output=True,
                text=True,timeout=6)
            row("emulator executable starts",details.returncode==0,
                "Reinstall the signed official package.")
            version=(details.stdout or details.stderr).strip().splitlines()[0][:120]
        except (OSError,subprocess.TimeoutExpired):
            version="unknown"
            row("emulator executable starts",False,
                "Check executable permissions and Linux dependencies.")
    else:version="not installed"
    row("emulator CA certificate",(CREDDIR/"ca.pem").is_file(),
        "Start the emulator; it generates a local CA per running instance.")
    try:
        emulator_keys()
        key_ok=True
    except (LocalError,OSError,ValueError,KeyError):
        key_ok=False
    row("emulator-issued credentials",key_ok,
        "Start the emulator; never use credentials from a real AWS profile.")
    reachable=health()
    row("local HTTPS health",reachable.get("running",False),
        "Start the emulator on loopback port %s and check its local log." % PORT)
    account=None
    if reachable.get("running") and key_ok:
        try:account=identity().get("Account")
        except (LocalError,ValueError,OSError,ET.ParseError):pass
    row("isolated STS account",account=="000000000000",
        "Check local credentials/CA. Refusing a non-emulator identity.")
    return {"ready":all(x["passed"] for x in checks),
            "endpoint":ENDPOINT,"port":PORT,"emulator_version":version,
            "account_verified":account=="000000000000",
            "checks":checks}

def start():
    if health()["running"]: return {"action":"already_running",**status()}
    binary=emulator_binary()
    if not binary: raise LocalError("Official emulator not installed: run scripts/install_wsl.sh")
    WORKDIR.mkdir(parents=True,exist_ok=True)
    with (WORKDIR/f"emulator-{PORT}.log").open("ab") as log:
        proc=subprocess.Popen([binary,"-p",str(PORT),"--telemetry","off"],
              stdin=subprocess.DEVNULL,stdout=log,stderr=subprocess.STDOUT,
              start_new_session=True,cwd=WORKDIR)
    PIDFILE.write_text(str(proc.pid))
    for i in range(40):
        if proc.poll() is not None:
            raise LocalError(f"Emulator exited {proc.returncode}; check emulator-{PORT}.log")
        if health()["running"]: return {"action":"started","pid":proc.pid,**status()}
        time.sleep(0.25)
    raise LocalError("Emulator startup timeout; inspect local emulator log")

def stop():
    if not PIDFILE.is_file(): raise LocalError("No MCP-managed emulator; refusing to stop other processes")
    pid=int(PIDFILE.read_text().strip())
    path=Path(f"/proc/{pid}/cmdline")
    if not path.exists():
        PIDFILE.unlink(missing_ok=True)
        return {"action":"already_stopped"}
    command=path.read_bytes().replace(b"\0",b" ").decode(errors="replace")
    if "aws-emulator" not in command or f"-p {PORT}" not in command:
        raise LocalError("PID changed: refusing to terminate unrelated process")
    os.kill(pid,signal.SIGTERM)
    PIDFILE.unlink(missing_ok=True)
    return {"action":"stop_requested","pid":pid}

def identity():
    payload=urlencode({"Action":"GetCallerIdentity","Version":"2011-06-15"}).encode()
    r=request("POST","/",service="sts",body=payload,
              headers={"content-type":"application/x-www-form-urlencoded; charset=utf-8"})
    d={x.tag.split("}")[-1]:x.text for x in parse_emulator_xml(r["body"]).iter()
       if x.tag.split("}")[-1] in ("Account","Arn","UserId")}
    if d.get("Account")!="000000000000":
        raise LocalError("Account is not the isolated emulator account")
    return d

def check_bucket(bucket):
    if not isinstance(bucket,str) or not re.fullmatch(r"[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]",bucket) or ".." in bucket:
        raise LocalError("Invalid S3 bucket name")
    return bucket

def check_table(table):
    if not isinstance(table,str) or not re.fullmatch(r"[A-Za-z0-9_.-]{3,255}",table):
        raise LocalError("Invalid DynamoDB table name")
    return table

def object_path(bucket,key):
    check_bucket(bucket)
    if not isinstance(key,str) or not 1<=len(key)<=1024 or key.startswith("/"):
        raise LocalError("Invalid object key")
    if any(part in ("",".","..") for part in key.split("/")) or any(ord(c)<32 for c in key):
        raise LocalError("Unsafe S3 key path component")
    return f"/{bucket}/{key}"

def s3_create_bucket(bucket):
    bucket=check_bucket(bucket)
    r=request("PUT",f"/{bucket}",service="s3")
    return {"bucket":bucket,"status":r["status"]}

def s3_list_buckets():
    r=request("GET","/",service="s3")
    root=parse_emulator_xml(r["body"])
    buckets=[]
    for node in root.iter():
        if node.tag.split("}")[-1]=="Buckets":
            for bucket in node:
                for field in bucket:
                    if field.tag.split("}")[-1]=="Name": buckets.append(field.text or "")
    return {"buckets":buckets}

def s3_list_objects(bucket):
    bucket=check_bucket(bucket)
    r=request("GET",f"/{bucket}",service="s3",query={"list-type":"2"})
    root=parse_emulator_xml(r["body"])
    keys=[]
    for node in root.iter():
        if node.tag.split("}")[-1]=="Contents":
            for field in node:
                if field.tag.split("}")[-1]=="Key": keys.append(field.text or "")
    return {"bucket":bucket,"keys":keys}

def s3_put_object(bucket,key,text):
    if not isinstance(text,str) or len(text.encode())>65536:
        raise LocalError("text must be at most 64 KiB")
    r=request("PUT",object_path(bucket,key),service="s3",body=text.encode(),
              headers={"content-type":"text/plain; charset=utf-8"})
    return {"bucket":bucket,"key":key,"status":r["status"],"etag":r["headers"].get("ETag")}

def s3_get_object(bucket,key):
    r=request("GET",object_path(bucket,key),service="s3")
    return {"bucket":bucket,"key":key,"text":r["body"].decode("utf-8"),"bytes":len(r["body"])}

def s3_delete_object(bucket,key):
    r=request("DELETE",object_path(bucket,key),service="s3")
    return {"deleted":True,"status":r["status"]}

def s3_delete_bucket(bucket):
    bucket=check_bucket(bucket)
    r=request("DELETE",f"/{bucket}",service="s3")
    return {"bucket":bucket,"deleted":True,"status":r["status"]}

def dynamo(operation,payload):
    body=json.dumps(payload,separators=(",",":")).encode()
    r=request("POST","/",service="dynamodb",body=body,headers={
        "content-type":"application/x-amz-json-1.0",
        "x-amz-target":"DynamoDB_20120810."+operation})
    return json.loads(r["body"]) if r["body"] else {}

def dynamodb_create_table(table):
    check_table(table)
    data=dynamo("CreateTable",{"TableName":table,
        "AttributeDefinitions":[{"AttributeName":"id","AttributeType":"S"}],
        "KeySchema":[{"AttributeName":"id","KeyType":"HASH"}],
        "BillingMode":"PAY_PER_REQUEST"})
    for attempt in range(40):
        try:
            described=dynamo("DescribeTable",{"TableName":table})
            state=described.get("Table",{}).get("TableStatus")
            if state=="ACTIVE":
                return {"table":table,"description":described["Table"]}
        except LocalError as exc:
            if "ResourceNotFoundException" not in str(exc): raise
        time.sleep(0.2)
    raise LocalError(f"Emulated DynamoDB table {table} did not become ACTIVE")

def dynamodb_put_item(table,item_id,message):
    check_table(table)
    data=dynamo("PutItem",{"TableName":table,"Item":{
        "id":{"S":str(item_id)},"message":{"S":str(message)}}})
    return {"table":table,"id":str(item_id),"result":data}

def dynamodb_get_item(table,item_id):
    check_table(table)
    return dynamo("GetItem",{"TableName":table,"Key":{"id":{"S":str(item_id)}}})

def dynamodb_delete_table(table):
    check_table(table)
    result=dynamo("DeleteTable",{"TableName":table})
    for attempt in range(40):
        names=dynamo("ListTables",{}).get("TableNames",[])
        if table not in names: return {"deleted":True,"table":table,"result":result}
        time.sleep(.2)
    raise LocalError(f"Emulated DynamoDB table {table} did not finish deleting")

def dynamodb_list_tables():
    return dynamo("ListTables",{})

def dynamodb_describe_table(table):
    check_table(table)
    return dynamo("DescribeTable",{"TableName":table})

# SQS is deliberately accessed only through the emulator's signed loopback URL.
def check_queue(name):
    if not isinstance(name,str) or not re.fullmatch(r"[A-Za-z0-9_-]{1,80}",name):
        raise LocalError("Invalid SQS standard queue name")
    return name

def _sqs_queue_url(queue):
    check_queue(queue)
    return f"{ENDPOINT}/000000000000/{queue}"

def sqs_query(action,arguments=None):
    # AWS Emulator implements the AWS JSON 1.0 protocol for SQS.
    body=json.dumps(arguments or {},separators=(",",":")).encode("utf-8")
    r=request("POST","/",service="sqs",body=body,
              headers={"content-type":"application/x-amz-json-1.0",
                       "x-amz-target":"AmazonSQS."+action})
    return json.loads(r["body"]) if r["body"] else {}

def sqs_create_queue(queue):
    check_queue(queue)
    result=sqs_query("CreateQueue",{"QueueName":queue})
    if not result.get("QueueUrl"): raise LocalError("SQS did not return QueueUrl")
    return {"queue":queue,"created":True,"queue_url":_sqs_queue_url(queue)}

def sqs_list_queues():
    # Emulator may return AWS-hosted URLs. Never expose them as usable endpoints.
    from urllib.parse import urlsplit
    result=sqs_query("ListQueues")
    names=[]
    for url in result.get("QueueUrls",[]):
        path=urlsplit(url).path.split("/")
        if len(path)==3 and path[1]=="000000000000":
            try: names.append(check_queue(path[2]))
            except LocalError: continue
    return {"queues":names}

def sqs_send_message(queue,message):
    check_queue(queue)
    if not isinstance(message,str) or not message or len(message.encode("utf-8"))>65536:
        raise LocalError("SQS message must be 1-65536 bytes")
    result=sqs_query("SendMessage",{"QueueUrl":_sqs_queue_url(queue),"MessageBody":message})
    if not result.get("MessageId"): raise LocalError("SQS did not return MessageId")
    return {"queue":queue,"message_id":result["MessageId"]}

def sqs_receive_messages(queue):
    check_queue(queue)
    result=sqs_query("ReceiveMessage",{"QueueUrl":_sqs_queue_url(queue),
                                       "MaxNumberOfMessages":1,"WaitTimeSeconds":0})
    messages=[]
    for m in result.get("Messages",[]):
        messages.append({k:m.get(k) for k in ("MessageId","Body","ReceiptHandle")})
    return {"queue":queue,"messages":messages}

def sqs_delete_message(queue,receipt_handle):
    check_queue(queue)
    if not isinstance(receipt_handle,str) or not 1<=len(receipt_handle)<=4096:
        raise LocalError("Invalid SQS receipt handle")
    sqs_query("DeleteMessage",{"QueueUrl":_sqs_queue_url(queue),"ReceiptHandle":receipt_handle})
    return {"queue":queue,"deleted":True}

def sqs_delete_queue(queue):
    check_queue(queue)
    sqs_query("DeleteQueue",{"QueueUrl":_sqs_queue_url(queue)})
    return {"queue":queue,"deleted":True}

def emulator_self_test():
    """Run isolated S3, DynamoDB and SQS checks; clean up only minted resources."""
    import secrets
    suffix=secrets.token_hex(5)
    bucket="mcp-selftest-"+suffix
    table="mcp_selftest_"+suffix
    queue="mcp_selftest_"+suffix
    began=time.perf_counter()
    checks=[]
    cleanup=[]
    observed_account=None
    created={"bucket":False,"table":False,"queue":False}
    def check(name,fn):
        tick=time.perf_counter()
        try:
            value=fn()
        except Exception:
            checks.append({"check":name,"passed":False,
                           "latency_ms":round(1000*(time.perf_counter()-tick),1)})
            raise
        checks.append({"check":name,"passed":True,
                       "latency_ms":round(1000*(time.perf_counter()-tick),1)})
        return value
    error=None
    try:
        state=check("health",health)
        if not state["running"]: raise LocalError("Emulator not healthy")
        ident=check("STS identity",identity)
        observed_account=ident.get("Account")
        if observed_account!="000000000000":
            raise LocalError("Unexpected emulator account")
        check("S3 create bucket",lambda:s3_create_bucket(bucket))
        created["bucket"]=True
        check("S3 put object",lambda:s3_put_object(bucket,"selftest.txt","checked-local"))
        item=check("S3 get object",lambda:s3_get_object(bucket,"selftest.txt"))
        if item["text"]!="checked-local":raise LocalError("S3 content mismatch")
        listed=check("S3 list objects",lambda:s3_list_objects(bucket))
        if "selftest.txt" not in listed["keys"]:raise LocalError("S3 list mismatch")
        check("DynamoDB create and wait",lambda:dynamodb_create_table(table))
        created["table"]=True
        check("DynamoDB put item",lambda:dynamodb_put_item(table,"check","ok"))
        row=check("DynamoDB get item",lambda:dynamodb_get_item(table,"check"))
        if row.get("Item",{}).get("message",{}).get("S")!="ok":
            raise LocalError("DynamoDB item mismatch")
        check("SQS create queue",lambda:sqs_create_queue(queue))
        created["queue"]=True
        check("SQS send message",lambda:sqs_send_message(queue,"safe-message"))
        messages=[]
        for retry in range(5):
            result=check("SQS receive message",lambda:sqs_receive_messages(queue))
            messages=result["messages"]
            if messages:break
            time.sleep(.1)
        if not messages or messages[0]["Body"]!="safe-message":
            raise LocalError("SQS message mismatch")
        check("SQS delete message",lambda:sqs_delete_message(queue,messages[0]["ReceiptHandle"]))
    except Exception as exc:
        error=str(exc) if isinstance(exc,(LocalError,ValueError)) else "Unexpected self-test failure"
    finally:
        # Only act on names minted in this call; never on caller resources.
        jobs=[]
        if created["queue"]: jobs.append(("SQS delete queue",lambda:sqs_delete_queue(queue)))
        if created["table"]: jobs.append(("DynamoDB delete table",lambda:dynamodb_delete_table(table)))
        if created["bucket"]:
            jobs.append(("S3 delete test object",lambda:s3_delete_object(bucket,"selftest.txt")))
            jobs.append(("S3 delete bucket",lambda:s3_delete_bucket(bucket)))
        for name,fn in jobs:
            try:
                fn()
                cleanup.append({"check":name,"passed":True})
            except Exception as exc:
                cleanup.append({"check":name,"passed":False,
                                "detail":str(exc)[:240]})
    passed=error is None and all(x["passed"] for x in cleanup)
    return {"passed":passed,"endpoint":ENDPOINT,"account":observed_account,
            "elapsed_ms":round(1000*(time.perf_counter()-began),1),
            "checks":checks,"cleanup":cleanup,
            "error":error if error else None}

def emulator_order_demo():
    """Synthetic order workflow; run-specific resources and deterministic repair."""
    import secrets
    suffix=secrets.token_hex(5)
    order_id="order-"+suffix
    bucket="mcp-order-"+suffix
    table="mcp_order_"+suffix
    queue="mcp_order_"+suffix
    receipt_key="receipts/"+order_id+".json"
    order={"id":order_id,"sku":"CODEGYM-DEMO-001","quantity":2,
           "total_usd":"42.00","status":"simulated"}
    order_json=json.dumps(order,sort_keys=True,separators=(",",":"))
    created={"bucket":False,"table":False,"queue":False}
    checks=[];cleanups=[];recovery=[];error=None
    begin=time.perf_counter()
    def step(name,fn):
        start=time.perf_counter()
        try:
            value=fn()
        except Exception:
            checks.append({"name":name,"passed":False,
                           "duration_ms":round((time.perf_counter()-start)*1000,1)})
            raise
        checks.append({"name":name,"passed":True,
                       "duration_ms":round((time.perf_counter()-start)*1000,1)})
        return value
    try:
        status=step("health",health)
        if not status["running"]:raise LocalError("Emulator not healthy")
        account=step("isolated STS identity",identity)["Account"]
        if account!="000000000000":raise LocalError("Wrong account")
        step("create S3 receipt bucket",lambda:s3_create_bucket(bucket))
        created["bucket"]=True
        step("create DynamoDB orders table",lambda:dynamodb_create_table(table))
        created["table"]=True
        step("create SQS order queue",lambda:sqs_create_queue(queue))
        created["queue"]=True

        # Controlled failure: request a receipt before it exists, then repair.
        try:
            s3_get_object(bucket,receipt_key)
        except LocalError as exc:
            if "HTTP 404" not in str(exc):raise
            recovery.append({"step":"read missing receipt",
                             "expected_error":"S3 404 Not Found","passed":True})
        else:
            raise LocalError("Missing receipt unexpectedly existed")

        step("write order record",
             lambda:dynamodb_put_item(table,order_id,order_json))
        step("repair by writing receipt",
             lambda:s3_put_object(bucket,receipt_key,order_json))
        step("enqueue order ID",lambda:sqs_send_message(queue,order_id))
        messages=[]
        for _ in range(6):
            received=step("receive queued order",lambda:sqs_receive_messages(queue))
            messages=received["messages"]
            if messages:break
            time.sleep(0.1)
        if not messages or messages[0].get("Body")!=order_id:
            raise LocalError("Queue did not return expected order ID")
        step("acknowledge queue message",lambda:sqs_delete_message(
            queue,messages[0]["ReceiptHandle"]))
        stored=step("read DynamoDB order",
                    lambda:dynamodb_get_item(table,order_id))
        saved=stored.get("Item",{}).get("message",{}).get("S")
        if saved!=order_json:raise LocalError("DynamoDB order content mismatch")
        receipt=step("read recovered S3 receipt",
                     lambda:s3_get_object(bucket,receipt_key))
        if receipt["text"]!=order_json:raise LocalError("S3 receipt mismatch")
        recovery.append({"step":"receipt readback after repair","passed":True})
    except Exception as exc:
        error=str(exc)[:300] if isinstance(exc,(LocalError,ValueError)) else "Unexpected order-demo failure"
    finally:
        actions=[]
        if created["queue"]:
            actions.append(("delete demo SQS queue",
                            lambda:sqs_delete_queue(queue)))
        if created["table"]:
            actions.append(("delete demo DynamoDB table",
                            lambda:dynamodb_delete_table(table)))
        if created["bucket"]:
            actions.append(("delete demo S3 receipt",
                            lambda:s3_delete_object(bucket,receipt_key)))
            actions.append(("delete demo S3 bucket",
                            lambda:s3_delete_bucket(bucket)))
        for name,fn in actions:
            try:
                fn()
                cleanups.append({"name":name,"passed":True})
            except Exception:
                cleanups.append({"name":name,"passed":False,
                                 "detail":"Cleanup action failed; inspect local emulator"})
    ok=error is None and len(recovery)==2 and all(c["passed"] for c in cleanups)
    return {"passed":ok,"order_id":order_id,
            "synthetic_order":order,
            "resources":{"bucket":bucket,"table":table,"queue":queue},
            "steps":checks,"recovery":recovery,"cleanup":cleanups,
            "duration_ms":round(1000*(time.perf_counter()-begin),1),
            "error":error}

